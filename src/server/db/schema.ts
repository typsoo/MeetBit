// The short id doubles as the URL segment of /e/<id>, so it is not a serial:
// it is an opaque string generated by the server on creation.
export const event = pgTable(
  "event",
  {
    id: text("id").primaryKey(),
    name: text("name").notNull(),
    description: text("description"),
    ownerUserId: text("owner_user_id")
      .notNull()
      .references(() => user.id, { onDelete: "cascade" }),
    // IANA timezone name ("Europe/Warsaw"), not a UTC offset: it survives
    // DST transitions. Never updated after creation (ADR-0002).
    timezone: text("timezone").notNull(),
    // Dates are plain 'YYYY-MM-DD' strings in the event's timezone, and
    // working hours are minutes-from-midnight integers: the grid math is
    // slotNumber * stepMinutes + workStartMinutes (ADR-0002).
    startDate: date("start_date", { mode: "string" }).notNull(),
    endDate: date("end_date", { mode: "string" }).notNull(),
    workStartMinutes: integer("work_start_minutes").notNull(),
    workEndMinutes: integer("work_end_minutes").notNull(),
    stepMinutes: integer("step_minutes").notNull(),
    status: text("status").notNull().default("open"),
    // Set only by event.approveSlot (ticket 16), never by user input.
    approvedDate: date("approved_date", { mode: "string" }),
    approvedSlot: integer("approved_slot"),
    createdAt: timestamp("created_at").defaultNow().notNull(),
  },
  (table) => [
    index("event_ownerUserId_idx").on(table.ownerUserId),
    // Row-level invariants as a safety net for server-side writes that
    // bypass input validation. Cross-field ordering (end >= start,
    // workEnd > workStart) is enforced by zod at the API boundary instead.
    check("event_step_minutes_check", sql`${table.stepMinutes} in (30, 60)`),
    check("event_status_check", sql`${table.status} in ('open', 'approved')`),
  ],
);

export const userRelations = relations(user, ({ many }) => ({
  sessions: many(session),
  accounts: many(account),
  events: many(event),
}));

export const sessionRelations = relations(session, ({ one }) => ({
  user: one(user, {
    fields: [session.userId],
    references: [user.id],
  }),
}));

export const accountRelations = relations(account, ({ one }) => ({
  user: one(user, {
    fields: [account.userId],
    references: [user.id],
  }),
}));

export const eventRelations = relations(event, ({ one }) => ({
  owner: one(user, {
    fields: [event.ownerUserId],
    references: [user.id],
  }),
}));
